import os
import json
import joblib
import pandas as pd
from typing import Dict, Any
from utils.trainer import FEATURE_COLUMNS, train_and_save_model

MODEL_DIR = os.path.join(os.path.dirname(__file__), "..", "models")
MODEL_PATH = os.path.join(MODEL_DIR, "candidate_success_model.joblib")
META_PATH = os.path.join(MODEL_DIR, "model_metadata.json")

_MODEL = None
_METADATA = None

def get_model_and_metadata():
    global _MODEL, _METADATA
    if _MODEL is None or _METADATA is None:
        if not os.path.exists(MODEL_PATH) or not os.path.exists(META_PATH):
            print("[Info] Trained model not found. Running trainer script to generate model artifacts...")
            _METADATA = train_and_save_model()
        else:
            with open(META_PATH, "r", encoding="utf-8") as f:
                _METADATA = json.load(f)
        
        _MODEL = joblib.load(MODEL_PATH)

    return _MODEL, _METADATA

def predict_candidate_success(features_input: Dict[str, Any]) -> Dict[str, Any]:
    """
    Predicts candidate recruitment success/suitability using trained Scikit-learn RandomForest model.
    """
    if not features_input or not isinstance(features_input, dict):
        raise ValueError("Input parameters must be a non-empty dictionary.")

    # 1. Input Validation & Default Population
    skill_match = float(features_input.get("skillMatchPercentage", 0.0))
    sem_sim = float(features_input.get("semanticSimilarityPercentage", 0.0))
    experience = float(features_input.get("relevantExperienceYears", 0.0))
    interview = float(features_input.get("interviewScore", 70.0))
    assessment = float(features_input.get("assessmentScore", 70.0))
    req_matched = int(features_input.get("requiredSkillsMatched", 0))
    total_req = int(features_input.get("totalRequiredSkills", 1))
    skill_gap = float(features_input.get("skillGapPercentage", 100.0 - skill_match))

    if not (0.0 <= skill_match <= 100.0):
        raise ValueError("skillMatchPercentage must be between 0 and 100.")
    if not (0.0 <= sem_sim <= 100.0):
        raise ValueError("semanticSimilarityPercentage must be between 0 and 100.")
    if not (0.0 <= experience <= 50.0):
        raise ValueError("relevantExperienceYears must be between 0 and 50.")
    if not (0.0 <= interview <= 100.0):
        raise ValueError("interviewScore must be between 0 and 100.")
    if not (0.0 <= assessment <= 100.0):
        raise ValueError("assessmentScore must be between 0 and 100.")
    if req_matched < 0 or total_req < 1:
        raise ValueError("requiredSkillsMatched must be >= 0 and totalRequiredSkills must be >= 1.")

    model, metadata = get_model_and_metadata()

    # 2. Prepare DataFrame for Prediction
    feature_row = {
        "skill_match_percentage": skill_match,
        "semantic_similarity_percentage": sem_sim,
        "relevant_experience_years": experience,
        "interview_score": interview,
        "assessment_score": assessment,
        "required_skills_matched": req_matched,
        "total_required_skills": total_req,
        "skill_gap_percentage": skill_gap
    }

    df_input = pd.DataFrame([feature_row])[FEATURE_COLUMNS]

    # 3. Model Inference
    probs = model.predict_proba(df_input)[0]
    pred_class = int(model.predict(df_input)[0])
    
    success_probability = round(float(probs[1]) * 100.0, 1)
    confidence = round(float(max(probs)), 2)

    # 4. Suitability Threshold Categorization
    if success_probability >= 80.0:
        suitability = "High Suitability"
    elif success_probability >= 60.0:
        suitability = "Moderate Suitability"
    else:
        suitability = "Low Suitability"

    return {
        "success": True,
        "prediction": pred_class,
        "successProbabilityPercentage": success_probability,
        "suitabilityLevel": suitability,
        "confidence": confidence,
        "featureValues": feature_row,
        "featureImportances": metadata.get("featureImportances", []),
        "modelEvaluationMetrics": metadata.get("metrics", {}),
        "modelVersion": metadata.get("modelVersion", "1.0.0"),
        "modelType": metadata.get("modelType", "RandomForestClassifier"),
        "datasetType": metadata.get("datasetType", "Synthetic development/demo dataset"),
        "disclaimer": metadata.get("disclaimer", "This prediction is generated by a Scikit-learn model trained on a synthetic demonstration dataset. Real organizational recruitment outcome data is required for production deployment.")
    }
